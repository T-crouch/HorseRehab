namespace HorseRehab.Core.Facilities;

/// <summary>
/// Defines equipment that may be required for rehabilitation exercises.
/// </summary>
public enum EquiptmentType
{
    /// <summary>
    /// An automated horse walker used for controlled exercise.
    /// </summary>
    Eurociser,
    /// <summary>
    /// Raised poles used for coordination, strength, and mobility exercises.
    /// </summary>
    Cavaletti,
    /// <summary>
    /// Pads used for balance and proprioception exercises.
    /// </summary>
    BalancePads,
    /// <summary>
    /// Ground poles used for coordination and movement exercises.
    /// </summary>
    GroundPoles,
    /// <summary>
    /// A treadmill used for controlled conditioning or rehabilitation.
    /// </summary>
    Treadmill
}